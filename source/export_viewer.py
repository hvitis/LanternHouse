"""Export the 3D viewer as a static website (GitHub Pages, or any static host). No FreeCAD needed.

    .venv/bin/python source/export_viewer.py _site     # then serve _site/ from any web server

The site contains source/viewer/, model data, the supplier DXF and a separate overlay of piece IDs, and the
3D-print page (prints.html) with the published prints from prints/. Every path is relative, so it also works
from a subfolder such as https://<user>.github.io/<repo>/.
The GitHub Actions workflow .github/workflows/ci.yml runs this on every push to main.
"""
import argparse, json, shutil
from pathlib import Path

import print_mesh
from serve import ROOT, VIEWER, model_data
from viewer_dxf import preview as viewer_cut_file

ASSETS = (
    'index.html', 'app.js', 'dxf-viewer.js', 'prints.html', 'prints.js', 'vendor/three.module.js',
    'vendor/OrbitControls.js', 'vendor/CSS2DRenderer.js', 'vendor/THREE-LICENSE.txt',
)
MARKER = '.moomin-viewer-export'

def export(dest):
    target=Path(dest).absolute()
    dest=target.resolve()
    # Only _site may be replaced inside the repository. Outside it, replace only our own exports.
    if target!=dest or dest in [ROOT,*ROOT.parents] or (ROOT in dest.parents and dest!=ROOT/'_site'):
        raise SystemExit(f'Refusing to replace {target}: choose _site or a new folder outside the repository.')
    if dest.exists() and (not dest.is_dir() or (dest!=ROOT/'_site' and not (dest/MARKER).is_file())):
        raise SystemExit(f'Refusing to replace {dest}: this is not a viewer export.')
    for asset in ASSETS:
        if not (VIEWER/asset).is_file():raise SystemExit(f'Missing viewer asset: {asset}')
    print(f'Building the model data for {dest.name}/ ...',flush=True)
    # Build and serialize before replacing a previous export, so config errors leave it intact.
    data=model_data()
    payload=json.dumps(data,separators=(',',':'),allow_nan=False)
    cut_drawing=viewer_cut_file(data)
    label_payload=json.dumps(cut_drawing['labels'],allow_nan=False)
    if dest.exists():shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for asset in ASSETS:
        path=dest/asset;path.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(VIEWER/asset,path)
    shutil.copyfile(ROOT/'LICENSE',dest/'HOUSE-LICENSE.txt')
    (dest/'.nojekyll').touch()
    (dest/MARKER).write_text('Generated by source/export_viewer.py\n',encoding='utf-8')
    (dest/'data').mkdir();(dest/'data/parts.json').write_text(payload,encoding='utf-8')
    (dest/'data/house.dxf').write_text(cut_drawing['dxf'],encoding='utf-8')
    (dest/'data/dxf-labels.json').write_text(label_payload,encoding='utf-8')
    export_prints(dest/'prints')
    size=sum(p.stat().st_size for p in dest.rglob('*') if p.is_file())
    print(f'Static viewer written to {dest} ({size/1024/1024:.1f} MB)')

def export_prints(dest):
    """The published 3D prints (prints/, generated on the Mac by `make prints`): the manifest and every file it lists."""
    manifest=ROOT/'prints/manifest.json'
    data=json.loads(manifest.read_text()) if manifest.exists() else {'printer':print_mesh.printer(),'small_parts':print_mesh.small_parts(),'parts':{}}
    dest.mkdir()
    for entry in data['parts'].values():
        for f in entry['files'].values():shutil.copyfile(ROOT/'prints'/f['path'],dest/f['path'])
    (dest/'manifest.json').write_text(json.dumps(data,separators=(',',':'),ensure_ascii=False),encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__.splitlines()[0]);p.add_argument('dest',help='output folder; it is replaced')
    export(p.parse_args().dest)
